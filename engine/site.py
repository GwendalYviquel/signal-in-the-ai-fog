"""Static pages of a show's catalog site, from its catalog.json and its structured episodes.

- <docs>/index.html: the catalog page (engine/templates/catalog.html), in the show's language;
  episodes.html for a show at the root of the site, whose index.html is the home page;
- <docs>/episodes/<date>.html: one page per episode (search engines and sharing), with chapters,
  every story with its reliability label, facts and read layers, sources and topics, and links
  to give feedback through a GitHub issue form;
- <docs>/topics/<slug>.html: everything said about a topic across episodes, newest first;
- <docs>/agenda.html: the dated items of every episode's What to watch, upcoming first, past ones
  greyed with a link to the episode that announced them;
- <docs>/topics/index.html, corrections.html, sitemap.xml and robots.txt.
And, for the whole site (write_shared): docs/index.html, the home page where a visitor picks a
show (every page has a button back to it), and docs/i18n.json, the interface texts of every
language for the EN | FR switch (docs/i18n.js).

Pages are written in the show's language; their interface texts carry data-i18n keys, so the
switch can translate them in the browser. Every text is escaped: titles, topics and sources come
from the web through Claude.

Usage: python -m engine.site   (rebuilds the catalog and every page of every show, or of SHOW)
"""
from __future__ import annotations

import datetime as dt
import json
import re
import subprocess
from html import escape
from pathlib import Path
from urllib.parse import urlencode

from . import locale
from .chapters import timestamp

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = Path(__file__).resolve().parent / "templates" / "catalog.html"
LABELS = ("confirmed", "reported", "unconfirmed")
GENERATED = "<!-- generated by engine/site.py: do not edit -->"


def slug(topic: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", topic.lower()).strip("-") or "topic"


def episode_url(base_url: str, date: str) -> str:
    return f"{base_url.rstrip('/')}/episodes/{date}.html"


def repo_from(base_url: str) -> str:
    """owner/repo of a GitHub Pages URL (https://owner.github.io/repo/), even in a show's folder."""
    m = re.match(r"https://([^./]+)\.github\.io/([^/]+)", base_url)
    return f"{m.group(1)}/{m.group(2)}" if m else ""


def _duration(seconds: int) -> str:
    return f"{seconds // 60} min {seconds % 60:02d} s" if seconds else ""


class Ui:
    """The interface of one show's pages: its language, and the way back to the site's shared files."""

    def __init__(self, cfg: dict):
        self.cfg = cfg
        self.loc = locale.of(cfg)
        self.lang = str(cfg.get("podcast", {}).get("language", "en"))[:2].lower()
        site_path = str(cfg.get("podcast", {}).get("site_path", "")).strip("/")
        self.shared = "../" * len(Path(site_path).parts) if site_path else ""  # from the show to docs/
        self.catalog = catalog_name(cfg)

    def key(self, name: str) -> str:
        """A key of the site texts; texts naming the period get the show's cadence ("story.week")."""
        value = self.loc["site"][name]
        return f"{name}.{locale.cadence(self.cfg)[0]}" if isinstance(value, dict) and "day" in value else name

    def text(self, name: str, **values) -> str:
        value = self.loc["site"][name]
        if isinstance(value, dict):
            value = value[locale.cadence(self.cfg)[0]] if "day" in value else value["one" if values.get("n") == 1 else "other"]
        return value.format(**values)

    def tag(self, name: str, element: str = "span", attrs: str = "", **values) -> str:
        """An element whose text the language switch can translate."""
        data = f" data-i18n-vars='{escape(json.dumps(values))}'" if values else ""
        return f'<{element}{attrs} data-i18n="{self.key(name)}"{data}>{escape(self.text(name, **values))}</{element}>'

    def date(self, iso: str) -> str:
        return (f'<span data-date="{iso}" data-date-style="long">'
                f'{escape(locale.page_date(dt.date.fromisoformat(iso), self.loc))}</span>')

    def switch(self) -> str:
        buttons = "".join(f'<button type="button" data-lang="{code}" aria-pressed="{str(code == self.lang).lower()}">'
                          f'{code.upper()}</button>' for code in languages())
        return f'<div class="lang-switch" role="group" aria-label="Language">{buttons}</div>'


def catalog_name(cfg: dict) -> str:
    """The catalog page's file: index.html, or episodes.html at the root, where index.html is the home page."""
    return "index.html" if str(cfg.get("podcast", {}).get("site_path", "")).strip("/") else "episodes.html"


def languages() -> list[str]:
    return sorted(p.stem for p in locale.LOCALES.glob("*.yaml"))


def _page(ui: Ui, title: str, description: str, canonical: str, cover: str, body: str, depth: str = "../",
          extra_head: str = "") -> str:
    shared = depth + ui.shared  # docs/, where pages.css, i18n.js and the home page live
    show_title = ui.cfg.get("podcast", {}).get("title", "")
    return f"""<!doctype html>
{GENERATED}
<html lang="{ui.lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<meta name="description" content="{escape(description)}">
<link rel="canonical" href="{escape(canonical)}">
<meta property="og:title" content="{escape(title)}">
<meta property="og:description" content="{escape(description)}">
<meta property="og:url" content="{escape(canonical)}">
<meta property="og:image" content="{escape(cover)}">
<meta name="twitter:card" content="summary">
<link rel="icon" href="{depth}cover.jpg">
<link rel="stylesheet" href="{shared}pages.css">
<script>try {{ const t = localStorage.getItem("theme"); if (t) document.documentElement.dataset.theme = t; }} catch {{}}</script>
<script src="{shared}i18n.js" defer></script>
{extra_head}</head>
<body>
<header class="bar"><div class="wrap">
  {_home_button(ui, shared)}
  <img src="{depth}cover.jpg" alt="">
  <a href="{depth}{ui.catalog}">{escape(show_title)}</a>
  <nav><a href="{depth}{ui.catalog}" data-i18n="nav_episodes">{escape(ui.text("nav_episodes"))}</a><a href="{depth}agenda.html" data-i18n="nav_agenda">{escape(ui.text("nav_agenda"))}</a><a href="{depth}topics/index.html" data-i18n="nav_topics">{escape(ui.text("nav_topics"))}</a></nav>
  {ui.switch()}
</div></header>
<main class="wrap">
{body}
</main>
<footer><div class="wrap">{ui.tag("footer")}
· <a href="{depth}corrections.html" data-i18n="nav_corrections">{escape(ui.text("nav_corrections"))}</a></div></footer>
</body>
</html>
"""


def _home_button(ui: Ui, shared: str) -> str:
    return (f'<a class="home" href="{shared}index.html" data-i18n-title="nav_home_title" '
            f'title="{escape(ui.text("nav_home_title"))}">← {ui.tag("nav_home")}</a>')


def _sources(ui: Ui, sources: list[dict]) -> str:
    primary = (f' <span class="primary" data-i18n="primary" data-i18n-title="primary_title" '
               f'title="{escape(ui.text("primary_title"))}">{escape(ui.text("primary"))}</span>')
    items = "".join(f'<li><a href="{escape(s["url"])}" rel="noopener" target="_blank">{escape(s["title"])}</a>'
                    + (primary if s.get("primary") is True else "") + "</li>"
                    for s in sources if str(s.get("url", "")).startswith("http"))
    return f'<ul class="sources">{items}</ul>' if items else ""


def _topic_tags(topics: list[str], depth: str = "../") -> str:
    if not topics:
        return ""
    tags = "".join(f'<a class="tag" href="{depth}topics/{slug(t)}.html">{escape(t)}</a>' for t in topics)
    return f'<div class="tags">{tags}</div>'


def _label(ui: Ui, label: str) -> str:
    if label not in LABELS:
        return ""
    return (f'<span class="label {label}" data-i18n="label_{label}" data-i18n-title="label_{label}_title" '
            f'title="{escape(ui.text(f"label_{label}_title"))}">{escape(ui.text(f"label_{label}"))}</span>')


def _story(ui: Ui, heading: str, story: dict) -> str:
    return (f'<section class="story"><h3>{heading} {_label(ui, story.get("label", ""))}</h3>'
            f'<p class="facts">{escape(story["facts"])}</p>'
            f'<p class="read"><span class="read-label" data-i18n="read">{escape(ui.text("read"))}</span>'
            f'{escape(story["read"])}</p>'
            f'{_topic_tags(story.get("topics") or [])}{_sources(ui, story.get("sources") or [])}</section>')


def _stories(ui: Ui, structured: dict) -> str:
    note = (f'<p class="note" data-i18n="labelled_after">{escape(ui.text("labelled_after"))}</p>'
            if structured.get("labelled_after_publication") else "")
    story = structured["story_of_the_day"]
    parts = [ui.tag("stories", "h2") + note,
             _story(ui, f'{ui.tag("story")} · {escape(story["theme"])}', story)]
    parts += [_story(ui, escape(s["theme"]), s) for s in structured["segments"]]
    if fu := structured.get("follow_up"):
        parts.append(f'{ui.tag("follow_up", "h2")}<p>{escape(fu["text"])}</p>{_sources(ui, [fu.get("source") or {}])}')
    num = structured["number_of_the_day"]
    parts.append(f'{ui.tag("number", "h2")}<p>{escape(num["text"])}</p>{_sources(ui, [num.get("source") or {}])}')
    parts.append(f'{ui.tag("watch", "h2")}<p>{escape(structured["what_to_watch"])}</p>')
    parts.append(f'{ui.tag("question", "h2")}<p>{escape(structured["question"])}</p>')
    return "\n".join(parts)


def _feedback(ui: Ui, repo: str, ep: dict) -> str:
    if not repo:
        return ""
    new = f"https://github.com/{repo}/issues/new?"
    # The forms add their own labels; "episode" pre-fills the form field of that id.
    useful = new + urlencode({"template": "episode-feedback.yml", "title": f"Feedback: {ep['title']}",
                              "episode": ep["date"]})
    topic = new + urlencode({"template": "topic-suggestion.yml"})
    return (f'<aside class="feedback"><p>{ui.tag("feedback_question", "strong")} {ui.tag("feedback_text")}</p>'
            f'<div class="actions">'
            f'<a href="{escape(useful)}" target="_blank" rel="noopener" data-i18n="feedback_give">'
            f'{escape(ui.text("feedback_give"))}</a>'
            f'<a href="{escape(topic)}" target="_blank" rel="noopener" data-i18n="feedback_topic">'
            f'{escape(ui.text("feedback_topic"))}</a></div>{ui.tag("feedback_note", "small")}</aside>')


def _corrections(ui: Ui, ep: dict) -> str:
    notes = []
    for c in ep.get("corrections") or []:
        aired = (f' <a href="{c["aired_in"]}.html">{ui.tag("correction_read", date=locale.page_date(dt.date.fromisoformat(c["aired_in"]), ui.loc))}</a>'
                 if c.get("aired_in") else " " + ui.tag("correction_next"))
        added = locale.page_date(dt.date.fromisoformat(c["added"]), ui.loc)
        notes.append(f'<aside class="correction">{ui.tag("correction", "strong", date=added)} '
                     f'{escape(c["text"])}{aired}</aside>')
    return "".join(notes)


def corrections_page(ui: Ui, episodes: list[dict], podcast: dict, base_url: str) -> str:
    base = base_url.rstrip("/") + "/"
    rows = [(c, ep) for ep in episodes for c in ep.get("corrections") or []]
    rows.sort(key=lambda r: r[0]["added"], reverse=True)
    items = "".join(f'<li><div class="when">{ui.date(c["added"])}</div><strong><a href="episodes/{ep["date"]}.html">'
                    f'{escape(ep["title"])}</a></strong> · {ui.date(ep["date"])}<p>{escape(c["text"])}</p></li>'
                    for c, ep in rows)
    body = (ui.tag("corrections_title", "h1") + ui.tag("corrections_lede", "p", ' class="lede"')
            + (f'<ol class="timeline">{items}</ol>' if items else ui.tag("no_correction", "p")))
    return _page(ui, f"{ui.text('corrections_title')} · {podcast['title']}", f"{ui.text('corrections_title')}: {podcast['title']}",
                 f"{base}corrections.html", base + podcast["cover"], body, depth="")


def _chapters(ui: Ui, chapters: list[dict]) -> str:
    if not chapters:
        return ""
    rows = "".join(f'<li><button type="button" data-t="{c["start"]}">{timestamp(c["start"])}</button>'
                   f'<span>{escape(c["title"])}</span></li>' for c in chapters)
    return (f'{ui.tag("chapters", "h2")}<ol class="chapters">{rows}</ol>'
            '<script>document.querySelectorAll(".chapters button").forEach((b) => b.addEventListener("click", () => {'
            ' const a = document.querySelector("audio"); if (!a) return; a.currentTime = Number(b.dataset.t); a.play(); }));'
            '</script>')


def _json_ld(data: dict) -> str:
    text = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")  # no tag can open inside the script
    return f'<script type="application/ld+json">{text}</script>\n'


def episode_page(ui: Ui, ep: dict, structured: dict | None, podcast: dict, base_url: str, repo: str,
                 newer: dict | None, older: dict | None) -> str:
    base = base_url.rstrip("/") + "/"
    canonical = episode_url(base_url, ep["date"])
    preview = ep["status"] == "preview"
    player = (f'<audio controls preload="none" src="{escape(ep["audio_url"])}"></audio>' if ep.get("audio_url")
              else ui.tag("audio_soon", "div", ' class="placeholder"'))
    spotify = podcast.get("spotify_url") or ""
    listen = player + (f'<a class="spotify" href="{escape(spotify)}" target="_blank" rel="noopener" '
                       f'data-i18n="listen_spotify">{escape(ui.text("listen_spotify"))}</a>' if spotify else "")
    meta = [ui.tag("preview" if preview else "published", "span", f' class="badge {"preview" if preview else "published"}"'),
            ui.date(ep["date"])]
    if ep.get("duration_seconds"):
        meta.append(f"<span>{_duration(ep['duration_seconds'])}</span>")
    headlines = "".join(f"<li>{escape(h)}</li>" for h in ep.get("headlines", []))
    content = _stories(ui, structured) if structured else (
        f'{ui.tag("script", "h2")}<div class="transcript">{escape(ep.get("transcript", ""))}</div>'
        f'{ui.tag("sources", "h2")}{_sources(ui, ep.get("sources", []))}')
    pager = '<nav class="pager">' + (
        f'<a href="{newer["date"]}.html">← {escape(newer["title"])}</a>' if newer else "<span></span>") + (
        f'<a href="{older["date"]}.html">{escape(older["title"])} →</a>' if older else "<span></span>") + "</nav>"
    body = (f'<div class="meta">{"".join(meta)}</div><h1>{escape(ep["title"])}</h1>'
            f'<p class="lede">{escape(ep["summary"])}</p>{_corrections(ui, ep)}<div class="listen">{listen}</div>'
            f'<ul class="headlines" aria-label="{escape(ui.text("headlines"))}" data-i18n-aria-label="headlines">{headlines}</ul>'
            f'{_topic_tags(ep.get("topics", []))}'
            f'{_chapters(ui, ep.get("chapters") or [])}{content}{_feedback(ui, repo, ep)}{pager}')
    ld = {"@context": "https://schema.org", "@type": "PodcastEpisode", "name": ep["title"],
          "description": ep["summary"], "datePublished": ep["date"], "url": canonical, "inLanguage": ui.lang,
          "partOfSeries": {"@type": "PodcastSeries", "name": podcast["title"], "url": base}}
    if ep.get("audio_url"):
        ld["associatedMedia"] = {"@type": "MediaObject", "contentUrl": ep["audio_url"]}
    return _page(ui, f"{ep['title']} · {podcast['title']}", ep["summary"], canonical, base + podcast["cover"],
                 body, extra_head=_json_ld(ld))


def topic_entries(episodes: list[dict], structured: dict[str, dict]) -> dict[str, list[dict]]:
    """{topic: [entry]} newest first; an entry is a story (structured episodes) or a whole episode."""
    found: dict[str, list[dict]] = {}
    for ep in episodes:
        st = structured.get(ep["date"])
        stories = ([("", st["story_of_the_day"])] + [(s["theme"], s) for s in st["segments"]] if st else [])
        seen = set()
        for theme, story in stories:
            for topic in story.get("topics") or []:
                seen.add(topic)
                found.setdefault(topic, []).append({"episode": ep, "theme": theme, "story": story})
        for topic in ep.get("topics", []):
            if topic not in seen:  # topic of an episode without structured data
                found.setdefault(topic, []).append({"episode": ep, "theme": None, "story": None})
    for entries in found.values():
        entries.sort(key=lambda e: e["episode"]["date"], reverse=True)
    return found


def _first_sentences(text: str, limit: int = 45) -> str:
    words = text.split()
    return " ".join(words[:limit]) + ("…" if len(words) > limit else "")


def topic_page(ui: Ui, topic: str, entries: list[dict], podcast: dict, base_url: str) -> str:
    base = base_url.rstrip("/") + "/"
    rows = []
    for e in entries:
        ep, story = e["episode"], e["story"]
        link = f'<a href="../episodes/{ep["date"]}.html">{escape(ep["title"])}</a>'
        if story:
            theme = escape(e["theme"]) if e["theme"] else ui.tag("story")  # "" is the story of the period
            rows.append(f'<li><div class="when">{ui.date(ep["date"])} · {theme} '
                        f'{_label(ui, story.get("label", ""))}</div><strong>{link}</strong>'
                        f'<p>{escape(_first_sentences(story["facts"]))}</p></li>')
        else:
            rows.append(f'<li><div class="when">{ui.date(ep["date"])}</div><strong>{link}</strong>'
                        f'<p>{escape(ep["summary"])}</p></li>')
    body = (f'<div class="meta"><a href="index.html" data-i18n="all_topics">{escape(ui.text("all_topics"))}</a></div>'
            f'<h1>{escape(topic)}</h1>{ui.tag("mentions", "p", " class=\"lede\"", n=len(entries))}'
            f'<ol class="timeline">{"".join(rows)}</ol>')
    return _page(ui, f"{topic} · {podcast['title']}", f"{topic}: {podcast['title']}",
                 f"{base}topics/{slug(topic)}.html", base + podcast["cover"], body)


def topics_index(ui: Ui, found: dict[str, list[dict]], podcast: dict, base_url: str) -> str:
    base = base_url.rstrip("/") + "/"
    ordered = sorted(found, key=lambda t: (-len(found[t]), t.lower()))
    tags = "".join(f'<a class="tag" href="{slug(t)}.html">{escape(t)} <span class="count">{len(found[t])}</span></a>'
                   for t in ordered)
    body = (ui.tag("topics_title", "h1") + ui.tag("topics_lede", "p", ' class="lede"')
            + f'<div class="topic-list">{tags or ui.tag("no_topic")}</div>')
    return _page(ui, f"{ui.text('topics_title')} · {podcast['title']}", f"{ui.text('topics_title')}: {podcast['title']}",
                 f"{base}topics/index.html", base + podcast["cover"], body)


def agenda_entries(episodes: list[dict], structured: dict[str, dict]) -> list[dict]:
    """Every dated item of the episodes' agenda, by date; the same item announced again keeps its latest episode."""
    from .generate import agenda_date
    found: dict[tuple[str, str], dict] = {}
    for ep in sorted(episodes, key=lambda e: e["date"]):  # oldest first: a later episode replaces it
        for item in (structured.get(ep["date"]) or {}).get("agenda") or []:
            if day := agenda_date(item):
                text = " ".join(str(item["text"]).split())
                found[(day, text.lower())] = {"date": day, "text": text, "episode": ep}
    return sorted(found.values(), key=lambda e: (e["date"], e["text"].lower()))


def agenda_page(ui: Ui, entries: list[dict], podcast: dict, base_url: str) -> str:
    """Items by date. The page stays the same from day to day: the browser moves past items, greyed,
    under their own heading (most recent first), so a rebuild never depends on the day it runs."""
    base = base_url.rstrip("/") + "/"
    rows = "".join(
        f'<li data-day="{e["date"]}"><div class="when">{ui.date(e["date"])}</div>'
        f'<strong>{escape(e["text"])}</strong> <a href="episodes/{e["episode"]["date"]}.html">'
        f'{ui.tag("agenda_from", date=locale.page_date(dt.date.fromisoformat(e["episode"]["date"]), ui.loc))}</a></li>'
        for e in entries)
    body = (ui.tag("agenda_title", "h1") + ui.tag("agenda_lede", "p", ' class="lede"')
            + ui.tag("agenda_upcoming", "h2")
            + f'<ol class="timeline agenda" id="upcoming">{rows}</ol>'
            + ui.tag("no_agenda", "p", ' id="no-agenda"' + ("" if not entries else " hidden"))
            + ui.tag("agenda_past", "h2", ' id="past-title" hidden') + '<ol class="timeline agenda" id="past"></ol>'
            + '<script>(() => { const d = new Date(), today = new Date(d.getTime() - d.getTimezoneOffset() * 60000)'
            '.toISOString().slice(0, 10); const past = document.getElementById("past");'
            ' const done = [...document.querySelectorAll("#upcoming li")].filter((li) => li.dataset.day < today);'
            ' done.reverse().forEach((li) => { li.classList.add("past"); past.append(li); });'
            ' if (done.length) document.getElementById("past-title").hidden = false;'
            ' if (!document.querySelector("#upcoming li")) document.getElementById("no-agenda").hidden = false; })();'
            '</script>')
    return _page(ui, f"{ui.text('agenda_title')} · {podcast['title']}", f"{ui.text('agenda_title')}: {podcast['title']}",
                 f"{base}agenda.html", base + podcast["cover"], body, depth="")


def catalog_page(ui: Ui) -> str:
    """The show's catalog page: the template, in the show's language, pointing to the shared files."""
    p = ui.cfg.get("podcast", {})
    values = {"LANG": ui.lang, "SHARED": ui.shared, "TITLE": escape(p.get("title", "")),
              "DESCRIPTION": escape(" ".join(str(p.get("description", "")).split()))}
    html = TEMPLATE.read_text(encoding="utf-8")
    for name, value in values.items():
        html = html.replace("{{" + name + "}}", value)
    return html.replace("<!doctype html>\n", f"<!doctype html>\n{GENERATED}\n", 1)


def _structured(data_dir: Path, ep: dict) -> dict | None:
    folder = data_dir / ("scripts" if ep["status"] == "published" else "previews")
    path = folder / f"{ep['date']}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def write_site(cfg: dict, catalog_json: Path, data_dir: Path, docs: Path, base_url: str) -> None:
    catalog = json.loads(catalog_json.read_text(encoding="utf-8"))
    podcast, episodes = catalog["podcast"], catalog["episodes"]
    ui = Ui(cfg)
    repo = repo_from(base_url)
    structured = {ep["date"]: st for ep in episodes if (st := _structured(data_dir, ep))}
    base = base_url.rstrip("/") + "/"

    pages: dict[Path, str] = {docs / ui.catalog: catalog_page(ui)}
    for i, ep in enumerate(episodes):  # newest first
        newer = episodes[i - 1] if i > 0 else None
        older = episodes[i + 1] if i + 1 < len(episodes) else None
        pages[docs / "episodes" / f"{ep['date']}.html"] = episode_page(
            ui, ep, structured.get(ep["date"]), podcast, base_url, repo, newer, older)
    found = topic_entries(episodes, structured)
    for topic, entries in found.items():
        pages[docs / "topics" / f"{slug(topic)}.html"] = topic_page(ui, topic, entries, podcast, base_url)
    pages[docs / "topics" / "index.html"] = topics_index(ui, found, podcast, base_url)
    pages[docs / "corrections.html"] = corrections_page(ui, episodes, podcast, base_url)
    pages[docs / "agenda.html"] = agenda_page(ui, agenda_entries(episodes, structured), podcast, base_url)

    for folder in ("episodes", "topics"):  # pages of removed episodes or topics
        (docs / folder).mkdir(parents=True, exist_ok=True)
        for old in (docs / folder).glob("*.html"):
            if old not in pages and GENERATED in old.read_text(encoding="utf-8"):
                old.unlink()
    for path, html in pages.items():
        path.write_text(html, encoding="utf-8")

    urls = [base] + [base + p.relative_to(docs).as_posix() for p in pages if p.name != "index.html" or p.parent != docs]
    (docs / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{escape(u)}</loc></url>\n" for u in urls) + "</urlset>\n", encoding="utf-8")
    (docs / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {base}sitemap.xml\n", encoding="utf-8")
    print(f"Site: {len(episodes)} episode pages, {len(found)} topic pages")


def i18n_json() -> dict:
    """Every language's site texts, texts naming the period flattened by cadence ("story.week")."""
    out = {}
    for code in languages():
        texts = {}
        for name, value in locale.load(code)["site"].items():
            if isinstance(value, dict) and "day" in value:
                texts.update({f"{name}.{period}": text for period, text in value.items()})
            else:
                texts[name] = value
        out[code] = texts
    return out


