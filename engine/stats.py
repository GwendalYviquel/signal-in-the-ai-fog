"""Listening stats: download counts of the episode MP3s, from GitHub releases.

Counts every download of an episode file: the catalog site's player, podcast apps that read the
RSS feed (Apple Podcasts, Overcast...), and Spotify's own copy (Spotify downloads the file once,
then serves listeners from its servers: its plays are in Spotify for Creators). One snapshot per
day is kept in data/stats.json; STATS.md and the catalog site are rebuilt from it.

Usage: python -m engine.stats   (see .github/workflows/stats.yml)
"""
from __future__ import annotations

import datetime as dt
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

def tag_pattern(prefix: str) -> re.Pattern:
    """Releases of one show: <release_prefix>-YYYY-MM-DD (other shows and rehearsals left out)."""
    return re.compile(re.escape(prefix) + r"-(\d{4}-\d{2}-\d{2})")


def fetch_releases(repo: str) -> list[dict]:
    """Every release, one compact JSON object per line (safe across pages)."""
    out = subprocess.run(["gh", "api", "--paginate", f"repos/{repo}/releases?per_page=100", "--jq",
                          ".[] | {tag_name, assets: [.assets[] | {name, download_count}]}"],
                         check=True, capture_output=True, text=True).stdout
    return [json.loads(line) for line in out.splitlines() if line.strip()]


def download_counts(releases: list[dict], prefix: str = "episode") -> dict[str, int]:
    """{episode date: downloads of its MP3}, the show's episode releases only (not tests or rehearsals)."""
    counts, tag = {}, tag_pattern(prefix)
    for r in releases:
        m = tag.fullmatch(r.get("tag_name", ""))
        if m:
            counts[m.group(1)] = sum(a.get("download_count", 0) for a in r.get("assets", [])
                                     if a.get("name", "").endswith(".mp3"))
    return counts


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"snapshots": {}}


def record(counts: dict[str, int], today: dt.date, path: Path) -> dict:
    """Store today's snapshot (a second run the same day replaces it)."""
    data = load(path)
    data["snapshots"][today.isoformat()] = dict(sorted(counts.items()))
    data["snapshots"] = dict(sorted(data["snapshots"].items()))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    return data


def latest(data: dict) -> dict[str, int]:
    snapshots = data.get("snapshots", {})
    return snapshots[max(snapshots)] if snapshots else {}


def build_report(data: dict, episodes: list[dict], today: dt.date) -> str:
    snapshots = data.get("snapshots", {})
    now = latest(data)
    week_ago = (today - dt.timedelta(days=7)).isoformat()
    base = snapshots[max(d for d in snapshots if d <= week_ago)] if any(d <= week_ago for d in snapshots) else {}
    titles = {e["date"]: e["title"] for e in episodes}
    months = defaultdict(int)
    for date, n in now.items():
        months[date[:7]] += n
    lines = [
        "# Stats",
        "",
        "Downloads of each episode's MP3, from GitHub releases. Generated by `engine/stats.py` from "
        "`data/stats.json` (one snapshot a day): do not edit by hand.",
        "",
        "They count the catalog site's player, podcast apps reading the RSS feed (Apple Podcasts, "
        "Overcast...) and Spotify's own copy of the file: Spotify downloads each episode once and serves "
        "its listeners itself, so Spotify plays are in Spotify for Creators, not here. Checks made while "
        "building the podcast add a few downloads to the first episodes.",
        "",
        f"**{sum(now.values()):,} downloads** in total, for {len(now)} episodes "
        f"(snapshot of {max(snapshots) if snapshots else 'never'}).",
        "",
        "## By month of publication",
        "",
        "| Month | Episodes | Downloads |",
        "| --- | ---: | ---: |",
    ]
    for month in sorted(months, reverse=True):
        lines.append(f"| {month} | {sum(1 for d in now if d.startswith(month))} | {months[month]:,} |")
    lines += ["", "## Episodes", "", "| Episode | Title | Downloads | Last 7 days |", "| --- | --- | ---: | ---: |"]
    for date in sorted(now, reverse=True):
        recent = now[date] - base.get(date, 0)
        lines.append(f"| {date} | {titles.get(date, '')} | {now[date]:,} | +{recent:,} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Every show: one snapshot of its download counts, its STATS.md and its catalog."""
    import os
    from . import catalog, main as pipeline, publish, show as shows
    releases = fetch_releases(os.environ.get("GITHUB_REPOSITORY") or publish.repo())
    for slug in shows.slugs():
        show = shows.load(slug)
        cfg = show.cfg
        today = pipeline.current_time(cfg).date()
        prefix = cfg["podcast"].get("release_prefix", slug)
        data = record(download_counts(releases, prefix), today, show.stats_ledger)
        episodes = pipeline.load(show.episodes)
        show.stats_report.write_text(build_report(data, episodes, today), encoding="utf-8")
        base_url = show.base_url("" if cfg["podcast"].get("base_url") else publish.pages_url())
        catalog.write_catalog(cfg, episodes, pipeline.load(show.previews), show.data, show.docs / "catalog.json",
                              base_url)
        print(f"{slug}: {sum(latest(data).values())} downloads over {len(latest(data))} episodes")


if __name__ == "__main__":
    main()
