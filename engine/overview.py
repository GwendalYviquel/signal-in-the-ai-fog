"""Reports across every show, with costs and usage kept strictly apart.

- shows/COSTS.md: money only. What every show consumed this month (Claude USD, ElevenLabs
  characters), the projection to the end of the month, and the total of ElevenLabs characters,
  one quota shared by every show. Cost per episode and per download is the only figure that
  uses the downloads, and it lives here. Rebuilt after every run (engine/costs.py).
- shows/STATS.md and shows/usage-dashboard-{light,dark}.svg: listening only, no money. Downloads
  per show, last 7 days, per episode, and new downloads per day over 30 days, stacked by show.
  Rebuilt with the daily stats (engine/stats.py).
Each show keeps its own COSTS.md (costs) and STATS.md (usage) in its folder.
"""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

from . import finops
from .drawing import THEMES, W, Drawing, text_width

DAYS = 30


def _load(path: Path, empty):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else empty


def _shows(repo: Path) -> list:
    from . import show as shows
    order = sorted(shows.slugs(repo), key=lambda s: (s != shows.DEFAULT, s))  # the first show first
    return [shows.load(s, repo) for s in order]


def _downloads(show) -> tuple[dict[str, int], dict[str, dict[str, int]]]:
    """(latest counts {episode date: downloads}, every snapshot {day: counts})."""
    snapshots = _load(show.stats_ledger, {"snapshots": {}}).get("snapshots", {})
    return (snapshots[max(snapshots)] if snapshots else {}), snapshots


def _published(runs: list[dict]) -> list[dict]:
    return [r for r in runs if r["mode"] == "publish" and r["outcome"] == "ok"]


def costs_report(repo: Path, today: dt.date) -> str:
    rows, total = [], {"runs": 0, "episodes": 0, "usd": 0.0, "chars": 0, "p_usd": 0.0, "p_chars": 0.0}
    lasting = []
    for show in _shows(repo):
        runs = _load(show.cost_ledger, [])
        s = finops.summary(runs, today, show.cfg)
        title = show.cfg["podcast"]["title"]
        p_usd = s["projection_usd"] if s["projection_usd"] is not None else s["claude_usd"]
        p_chars = s["projection_chars"] if s["projection_chars"] is not None else s["chars"]
        name = f"[{title}]({show.slug}/COSTS.md)" if show.cost_report.exists() else title
        rows.append(f"| {name} | {s['runs']} | {s['episodes']} | ${s['claude_usd']:.2f} | "
                    f"{s['chars']:,} | ${p_usd:.2f} | {p_chars:,.0f} |")
        for k, v in (("runs", s["runs"]), ("episodes", s["episodes"]), ("usd", s["claude_usd"]),
                     ("chars", s["chars"]), ("p_usd", p_usd), ("p_chars", p_chars)):
            total[k] += v
        published = _published(runs)
        usd = sum(finops.usd(r) for r in runs)  # every run: failures and checks are part of the cost
        chars = sum(r["elevenlabs_characters"] for r in runs)
        downloads = sum(_downloads(show)[0].values())
        lasting.append(
            f"| {title} | {len(published)} | "
            + (f"${usd / len(published):.2f} | {chars / len(published):,.0f} | " if published else "— | — | ")
            + f"{downloads:,} | " + (f"${usd / downloads:.3f} |" if downloads else "— |"))
    month = today.strftime("%B %Y")
    lines = [
        "# Costs, all shows",
        "",
        "Money only: what every show consumes, Claude and ElevenLabs. Listening is in [STATS.md](STATS.md). "
        "Generated by `engine/overview.py` after every run: do not edit by hand. Each show's own report, "
        "with every run, is linked from its name.",
        "",
        f"## This month ({month})",
        "",
        "The projection runs the cost of a published episode over the month's episode days (every weekday, "
        "or one day a week for a weekly show); a show without an episode yet counts what it spent so far.",
        "",
        "| Show | Runs | Episodes published | Claude (≈ USD) | ElevenLabs characters | Projection, Claude | "
        "Projection, characters |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
        *rows,
        f"| **All shows** | **{total['runs']}** | **{total['episodes']}** | **${total['usd']:.2f}** | "
        f"**{total['chars']:,}** | **${total['p_usd']:.2f}** | **{total['p_chars']:,.0f}** |",
        "",
        f"**ElevenLabs credits are one quota shared by every show**: {total['chars']:,} characters used this "
        f"month, about {total['p_chars']:,.0f} by the end of the month at this pace. Compare with the plan's "
        "monthly credits in the ElevenLabs account: when they run out, the voice check stops each run before "
        "it pays for a script.",
        "",
        "## Per episode and per download, since the first run",
        "",
        "Every run counts, failed ones and checks included: they are part of what an episode costs. Downloads "
        "are those of [STATS.md](STATS.md), which leave out Spotify's own plays: the cost per download is "
        "an upper bound.",
        "",
        "| Show | Episodes published | Claude per episode | ElevenLabs characters per episode | Downloads | "
        "Claude per download |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
        *lasting,
    ]
    return "\n".join(lines) + "\n"


def _new_per_day(snapshots: dict[str, dict[str, int]], days: list[dt.date]) -> dict[dt.date, int]:
    """Downloads added on each day: the difference with the previous snapshot (none before the first)."""
    ordered = sorted(snapshots)
    added = {}
    for before, after in zip(ordered, ordered[1:]):
        added[dt.date.fromisoformat(after)] = max(0, sum(snapshots[after].values()) - sum(snapshots[before].values()))
    return {d: added.get(d, 0) for d in days}


def usage(repo: Path, today: dt.date) -> list[dict]:
    week_ago = (today - dt.timedelta(days=7)).isoformat()
    days = [today - dt.timedelta(days=DAYS - 1 - i) for i in range(DAYS)]
    out = []
    for show in _shows(repo):
        now, snapshots = _downloads(show)
        older = [d for d in snapshots if d <= week_ago]
        base = snapshots[max(older)] if older else {}
        episodes = _load(show.episodes, [])
        out.append({"slug": show.slug, "title": show.cfg["podcast"]["title"], "episodes": len(episodes),
                    "downloads": sum(now.values()), "week": sum(now.values()) - sum(base.values()),
                    "snapshot": max(snapshots) if snapshots else "", "per_day": _new_per_day(snapshots, days),
                    "report": show.stats_report.exists()})
    return out


def usage_report(rows: list[dict]) -> str:
    lines = [
        "# Usage, all shows",
        "",
        "Listening only, no money: costs are in [COSTS.md](COSTS.md). Generated by `engine/overview.py` with "
        "the daily stats: do not edit by hand. Each show's own report, episode by episode, is linked from its name.",
        "",
        '<p align="center">',
        "  <picture>",
        '    <source media="(prefers-color-scheme: dark)" srcset="usage-dashboard-dark.svg">',
        '    <img src="usage-dashboard-light.svg" alt="Usage dashboard: downloads, last 7 days, episodes '
        'published, downloads per episode, and new downloads per day over 30 days by show" width="100%">',
        "  </picture>",
        "</p>",
        "",
        "Downloads of each episode's MP3: the catalog site's player, podcast apps reading the RSS feed, and "
        "Spotify's single copy of the file. Spotify plays are not available through an API: they are in "
        "Spotify for Creators only.",
        "",
        "| Show | Episodes published | Downloads | Last 7 days | Per episode | Snapshot |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in rows:
        per = f"{r['downloads'] / r['episodes']:.1f}" if r["episodes"] else "—"
        name = f"[{r['title']}]({r['slug']}/STATS.md)" if r.get("report") else r["title"]
        lines.append(f"| {name} | {r['episodes']} | {r['downloads']:,} | "
                     f"+{r['week']:,} | {per} | {r['snapshot'] or 'none yet'} |")
    return "\n".join(lines) + "\n"


def usage_svg(rows: list[dict], theme: str) -> str:
    colors = finops.SERIES[theme]
    d = Drawing(392, theme)
    c = d.c
    downloads, week = sum(r["downloads"] for r in rows), sum(r["week"] for r in rows)
    episodes = sum(r["episodes"] for r in rows)
    tiles = [("Downloads", f"{downloads:,}", "all shows, since the start"),
             ("Last 7 days", f"+{week:,}", "new downloads"),
             ("Episodes published", f"{episodes:,}", f"{len(rows)} shows"),
             ("Per episode", f"{downloads / episodes:.1f}" if episodes else "—", "downloads on average")]
    tw = (W - 2 - 3 * 12) / 4
    for i, (label, value, sub) in enumerate(tiles):
        x = 1 + i * (tw + 12)
        d.rect(x, 1, tw, 92, c["stage"], c["stage_stroke"], r=14)
        d.box(x + 4, 10, tw - 8, 74, [(label, 11.5, 600, c["muted"]), (value, 24, 750, c["ink"]),
                                      (sub, 11, 400, c["muted"])], "none", frame_visible=False)
    names = [r["title"] for r in rows]
    palette = [colors[i % len(colors)] for i in range(len(names))]
    lx, ly = 1, 118
    for name, color in zip(names, palette):
        d.rect(lx, ly - 10, 12, 12, color, r=3)
        bw = text_width(name, 12) + 14
        d.box(lx + 16, ly - 13, bw, 18, [(name, 12, 500, c["ink"])], "none", align="start", pad=2,
              frame_visible=False)
        lx += 16 + bw + 18
    days = sorted(rows[0]["per_day"]) if rows else []
    series = [(day, {r["title"]: float(r["per_day"][day]) for r in rows}) for day in days]
    if series:
        finops.chart(d, 1, 140, W - 2, 250, f"New downloads per day, last {DAYS} days",
                     series, lambda v: f"{v:.0f}" if v == int(v) else f"{v:.1f}", palette, kinds=names)
    return d.svg("Usage dashboard")


def write_costs(repo: Path, today: dt.date | None = None) -> Path:
    today = today or dt.datetime.now(finops.PARIS).date()
    path = repo / "shows" / "COSTS.md"
    path.write_text(costs_report(repo, today), encoding="utf-8")
    return path


def write_usage(repo: Path, today: dt.date | None = None) -> list[Path]:
    today = today or dt.datetime.now(finops.PARIS).date()
    rows = usage(repo, today)
    folder = repo / "shows"
    paths = [folder / "STATS.md"]
    paths[0].write_text(usage_report(rows), encoding="utf-8")
    for theme in THEMES:
        path = folder / f"usage-dashboard-{theme}.svg"
        path.write_text(usage_svg(rows, theme), encoding="utf-8")
        paths.append(path)
    return paths


if __name__ == "__main__":
    from . import show as shows
    write_costs(shows.REPO)
    write_usage(shows.REPO)
    print("shows/COSTS.md, shows/STATS.md and the usage dashboard rebuilt")
