"""Static pages of the catalog site, from docs/catalog.json and the structured episodes.

- docs/episodes/<date>.html: one page per episode (search engines and sharing), with chapters,
  every story with its reliability label, facts and read layers, sources and topics, and links
  to give feedback through a GitHub issue form;
- docs/topics/<slug>.html: everything said about a topic across episodes, newest first;
- docs/topics/index.html, docs/sitemap.xml and docs/robots.txt.
Every text is escaped: titles, topics and sources come from the web through Claude.

Usage: python -m podcast.site   (rebuilds the catalog and every page from the committed data)
"""
from __future__ import annotations

import datetime as dt
import json
import re
import subprocess
from html import escape
from pathlib import Path
from urllib.parse import urlencode

from .chapters import timestamp

ROOT = Path(__file__).resolve().parent.parent
LABELS = {
    "confirmed": ("Confirmed", "Announced by the company or authority itself, or a primary source"),
    "reported": ("Reported", "Reported by credible press, not confirmed by the company"),
    "unconfirmed": ("Unconfirmed", "A rumour, a leak or a single weak source"),
}
GENERATED = "<!-- generated by podcast/site.py: do not edit -->"


def slug(topic: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", topic.lower()).strip("-") or "topic"


def episode_url(base_url: str, date: str) -> str:
    return f"{base_url.rstrip('/')}/episodes/{date}.html"


def repo_from(base_url: str) -> str:
    """owner/repo of a GitHub Pages URL (https://owner.github.io/repo/)."""
    m = re.match(r"https://([^./]+)\.github\.io/([^/]+)", base_url)
    return f"{m.group(1)}/{m.group(2)}" if m else ""


def _day(iso: str) -> str:
    d = dt.date.fromisoformat(iso)
    return f"{d:%A} {d.day} {d:%B} {d.year}"


def _duration(seconds: int) -> str:
    return f"{seconds // 60} min {seconds % 60:02d} s" if seconds else ""


def _page(title: str, description: str, canonical: str, cover: str, body: str, depth: str = "../",
          extra_head: str = "") -> str:
    return f"""<!doctype html>
{GENERATED}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<meta name="description" content="{escape(description)}">
<link rel="canonical" href="{escape(canonical)}">
<meta property="og:title" content="{escape(title)}">
<meta property="og:description" content="{escape(description)}">
<meta property="og:url" content="{escape(canonical)}">
<meta property="og:image" content="{escape(cover)}">
<meta name="twitter:card" content="summary">
<link rel="icon" href="{depth}cover.jpg">
<link rel="stylesheet" href="{depth}pages.css">
<script>try {{ const t = localStorage.getItem("theme"); if (t) document.documentElement.dataset.theme = t; }} catch {{}}</script>
{extra_head}</head>
<body>
<header class="bar"><div class="wrap">
  <img src="{depth}cover.jpg" alt="">
  <a href="{depth}index.html">Signal in the AI Fog</a>
  <nav><a href="{depth}index.html">Episodes</a><a href="{depth}topics/index.html">Topics</a></nav>
</div></header>
<main class="wrap">
{body}
</main>
<footer><div class="wrap">Scripts are written and voices generated by AI. Sources are listed with every story.
· <a href="{depth}corrections.html">Corrections</a></div></footer>
</body>
</html>
"""


def _sources(sources: list[dict]) -> str:
    items = "".join(f'<li><a href="{escape(s["url"])}" rel="noopener" target="_blank">{escape(s["title"])}</a>'
                    + (' <span class="primary" title="The organisation\'s own publication">primary</span>'
                       if s.get("primary") is True else "") + "</li>"
                    for s in sources if str(s.get("url", "")).startswith("http"))
    return f'<ul class="sources">{items}</ul>' if items else ""


def _topic_tags(topics: list[str], depth: str = "../") -> str:
    if not topics:
        return ""
    tags = "".join(f'<a class="tag" href="{depth}topics/{slug(t)}.html">{escape(t)}</a>' for t in topics)
    return f'<div class="tags">{tags}</div>'


def _label(label: str) -> str:
    if label not in LABELS:
        return ""
    name, help_text = LABELS[label]
    return f'<span class="label {label}" title="{escape(help_text)}">{name}</span>'


def _story(heading: str, story: dict) -> str:
    return (f'<section class="story"><h3>{escape(heading)} {_label(story.get("label", ""))}</h3>'
            f'<p class="facts">{escape(story["facts"])}</p><p class="read">{escape(story["read"])}</p>'
            f'{_topic_tags(story.get("topics") or [])}{_sources(story.get("sources") or [])}</section>')


def _stories(structured: dict) -> str:
    note = ('<p class="note">Reliability labels added after publication, from each story\'s sources.</p>'
            if structured.get("labelled_after_publication") else "")
    parts = ["<h2>Stories</h2>" + note, _story(f"Story of the day · {structured['story_of_the_day']['theme']}",
                                        structured["story_of_the_day"])]
    parts += [_story(s["theme"], s) for s in structured["segments"]]
    if fu := structured.get("follow_up"):
        parts.append(f'<h2>Follow-up</h2><p>{escape(fu["text"])}</p>{_sources([fu.get("source") or {}])}')
    num = structured["number_of_the_day"]
    parts.append(f'<h2>Number of the day</h2><p>{escape(num["text"])}</p>{_sources([num.get("source") or {}])}')
    parts.append(f'<h2>What to watch</h2><p>{escape(structured["what_to_watch"])}</p>')
    parts.append(f'<h2>Question for your team</h2><p>{escape(structured["question"])}</p>')
    return "\n".join(parts)


def _feedback(repo: str, ep: dict) -> str:
    if not repo:
        return ""
    new = f"https://github.com/{repo}/issues/new?"
    # The forms add their own labels; "episode" pre-fills the form field of that id.
    useful = new + urlencode({"template": "episode-feedback.yml", "title": f"Feedback: {ep['title']}",
                              "episode": ep["date"]})
    topic = new + urlencode({"template": "topic-suggestion.yml"})
    return (f'<aside class="feedback"><p><strong>Was this episode useful?</strong> Tell what worked, '
            f'what did not, or suggest a topic to cover.</p><div class="actions">'
            f'<a href="{escape(useful)}" target="_blank" rel="noopener">Give feedback</a>'
            f'<a href="{escape(topic)}" target="_blank" rel="noopener">Suggest a topic</a></div>'
            f'<small>Opens a form on GitHub (a free account is needed). Issues are public: '
            f'never write anything personal or confidential.</small></aside>')


def _corrections(ep: dict) -> str:
    notes = []
    for c in ep.get("corrections") or []:
        aired = (f' Read in the episode of <a href="{c["aired_in"]}.html">{_day(c["aired_in"])}</a>.'
                 if c.get("aired_in") else " To be read in the next episode.")
        notes.append(f'<aside class="correction"><strong>Correction, {_day(c["added"])}.</strong> '
                     f'{escape(c["text"])}{aired}</aside>')
    return "".join(notes)


def corrections_page(episodes: list[dict], podcast: dict, base_url: str) -> str:
    base = base_url.rstrip("/") + "/"
    rows = [(c, ep) for ep in episodes for c in ep.get("corrections") or []]
    rows.sort(key=lambda r: r[0]["added"], reverse=True)
    items = "".join(f'<li><div class="when">{_day(c["added"])}</div><strong><a href="episodes/{ep["date"]}.html">'
                    f'{escape(ep["title"])}</a></strong> · {_day(ep["date"])}<p>{escape(c["text"])}</p></li>'
                    for c, ep in rows)
    body = ('<h1>Corrections</h1><p class="lede">When an episode gets something wrong, the correction is '
            'added here, on the episode page and in its description, and read in the next episode.</p>'
            + (f'<ol class="timeline">{items}</ol>' if items else "<p>No correction so far.</p>"))
    return _page(f"Corrections · {podcast['title']}", f"Corrections of {podcast['title']} episodes.",
                 f"{base}corrections.html", base + podcast["cover"], body, depth="")


def _chapters(chapters: list[dict]) -> str:
    if not chapters:
        return ""
    rows = "".join(f'<li><button type="button" data-t="{c["start"]}">{timestamp(c["start"])}</button>'
                   f'<span>{escape(c["title"])}</span></li>' for c in chapters)
    return (f'<h2>Chapters</h2><ol class="chapters">{rows}</ol>'
            '<script>document.querySelectorAll(".chapters button").forEach((b) => b.addEventListener("click", () => {'
            ' const a = document.querySelector("audio"); if (!a) return; a.currentTime = Number(b.dataset.t); a.play(); }));'
            '</script>')


def _json_ld(data: dict) -> str:
    text = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")  # no tag can open inside the script
    return f'<script type="application/ld+json">{text}</script>\n'


def episode_page(ep: dict, structured: dict | None, podcast: dict, base_url: str, repo: str,
                 newer: dict | None, older: dict | None) -> str:
    base = base_url.rstrip("/") + "/"
    canonical = episode_url(base_url, ep["date"])
    preview = ep["status"] == "preview"
    player = (f'<audio controls preload="none" src="{escape(ep["audio_url"])}"></audio>' if ep.get("audio_url")
              else '<div class="placeholder">Audio coming soon · script preview</div>')
    spotify = podcast.get("spotify_url") or ""
    listen = player + (f'<a class="spotify" href="{escape(spotify)}" target="_blank" rel="noopener">'
                       f'Listen on Spotify</a>' if spotify else "")
    meta = [f'<span class="badge {"preview" if preview else "published"}">{"Preview" if preview else "Published"}</span>',
            f"<span>{_day(ep['date'])}</span>"]
    if ep.get("duration_seconds"):
        meta.append(f"<span>{_duration(ep['duration_seconds'])}</span>")
    headlines = "".join(f"<li>{escape(h)}</li>" for h in ep.get("headlines", []))
    content = _stories(structured) if structured else (
        f'<h2>Script</h2><div class="transcript">{escape(ep.get("transcript", ""))}</div>'
        f'<h2>Sources</h2>{_sources(ep.get("sources", []))}')
    pager = '<nav class="pager">' + (
        f'<a href="{newer["date"]}.html">← {escape(newer["title"])}</a>' if newer else "<span></span>") + (
        f'<a href="{older["date"]}.html">{escape(older["title"])} →</a>' if older else "<span></span>") + "</nav>"
    body = (f'<div class="meta">{"".join(meta)}</div><h1>{escape(ep["title"])}</h1>'
            f'<p class="lede">{escape(ep["summary"])}</p>{_corrections(ep)}<div class="listen">{listen}</div>'
            f'<ul class="headlines" aria-label="Headlines">{headlines}</ul>{_topic_tags(ep.get("topics", []))}'
            f'{_chapters(ep.get("chapters") or [])}{content}{_feedback(repo, ep)}{pager}')
    ld = {"@context": "https://schema.org", "@type": "PodcastEpisode", "name": ep["title"],
          "description": ep["summary"], "datePublished": ep["date"], "url": canonical,
          "partOfSeries": {"@type": "PodcastSeries", "name": podcast["title"], "url": base}}
    if ep.get("audio_url"):
        ld["associatedMedia"] = {"@type": "MediaObject", "contentUrl": ep["audio_url"]}
    return _page(f"{ep['title']} · {podcast['title']}", ep["summary"], canonical, base + podcast["cover"],
                 body, extra_head=_json_ld(ld))


def topic_entries(episodes: list[dict], structured: dict[str, dict]) -> dict[str, list[dict]]:
    """{topic: [entry]} newest first; an entry is a story (structured episodes) or a whole episode."""
    found: dict[str, list[dict]] = {}
    for ep in episodes:
        st = structured.get(ep["date"])
        stories = ([("Story of the day", st["story_of_the_day"])] + [(s["theme"], s) for s in st["segments"]]
                   if st else [])
        seen = set()
        for theme, story in stories:
            for topic in story.get("topics") or []:
                seen.add(topic)
                found.setdefault(topic, []).append({"episode": ep, "theme": theme, "story": story})
        for topic in ep.get("topics", []):
            if topic not in seen:  # topic of an episode without structured data
                found.setdefault(topic, []).append({"episode": ep, "theme": "", "story": None})
    for entries in found.values():
        entries.sort(key=lambda e: e["episode"]["date"], reverse=True)
    return found


def _first_sentences(text: str, limit: int = 45) -> str:
    words = text.split()
    return " ".join(words[:limit]) + ("…" if len(words) > limit else "")


def topic_page(topic: str, entries: list[dict], podcast: dict, base_url: str) -> str:
    base = base_url.rstrip("/") + "/"
    rows = []
    for e in entries:
        ep, story = e["episode"], e["story"]
        link = f'<a href="../episodes/{ep["date"]}.html">{escape(ep["title"])}</a>'
        if story:
            rows.append(f'<li><div class="when">{_day(ep["date"])} · {escape(e["theme"])} '
                        f'{_label(story.get("label", ""))}</div><strong>{link}</strong>'
                        f'<p>{escape(_first_sentences(story["facts"]))}</p></li>')
        else:
            rows.append(f'<li><div class="when">{_day(ep["date"])}</div><strong>{link}</strong>'
                        f'<p>{escape(ep["summary"])}</p></li>')
    n = len(entries)
    body = (f'<div class="meta"><a href="index.html">All topics</a></div><h1>{escape(topic)}</h1>'
            f'<p class="lede">{n} mention{"s" if n != 1 else ""} across the episodes, newest first.</p>'
            f'<ol class="timeline">{"".join(rows)}</ol>')
    return _page(f"{topic} · {podcast['title']}", f"Everything {podcast['title']} said about {topic}, as a timeline.",
                 f"{base}topics/{slug(topic)}.html", base + podcast["cover"], body)


def topics_index(found: dict[str, list[dict]], podcast: dict, base_url: str) -> str:
    base = base_url.rstrip("/") + "/"
    ordered = sorted(found, key=lambda t: (-len(found[t]), t.lower()))
    tags = "".join(f'<a class="tag" href="{slug(t)}.html">{escape(t)} <span class="count">{len(found[t])}</span></a>'
                   for t in ordered)
    body = (f'<h1>Topics</h1><p class="lede">Companies, products, laws and subjects covered, by number of '
            f'mentions. Each page is a timeline of what was said.</p><div class="topic-list">{tags or "No topic yet."}</div>')
    return _page(f"Topics · {podcast['title']}", f"Every topic covered by {podcast['title']}.",
                 f"{base}topics/index.html", base + podcast["cover"], body)


def _structured(data_dir: Path, ep: dict) -> dict | None:
    folder = data_dir / ("scripts" if ep["status"] == "published" else "previews")
    path = folder / f"{ep['date']}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def write_site(cfg: dict, catalog_json: Path, data_dir: Path, docs: Path, base_url: str) -> None:
    catalog = json.loads(catalog_json.read_text(encoding="utf-8"))
    podcast, episodes = catalog["podcast"], catalog["episodes"]
    repo = repo_from(base_url)
    structured = {ep["date"]: st for ep in episodes if (st := _structured(data_dir, ep))}
    base = base_url.rstrip("/") + "/"

    pages: dict[Path, str] = {}
    for i, ep in enumerate(episodes):  # newest first
        newer = episodes[i - 1] if i > 0 else None
        older = episodes[i + 1] if i + 1 < len(episodes) else None
        pages[docs / "episodes" / f"{ep['date']}.html"] = episode_page(
            ep, structured.get(ep["date"]), podcast, base_url, repo, newer, older)
    found = topic_entries(episodes, structured)
    for topic, entries in found.items():
        pages[docs / "topics" / f"{slug(topic)}.html"] = topic_page(topic, entries, podcast, base_url)
    pages[docs / "topics" / "index.html"] = topics_index(found, podcast, base_url)
    pages[docs / "corrections.html"] = corrections_page(episodes, podcast, base_url)

    for folder in ("episodes", "topics"):  # pages of removed episodes or topics
        (docs / folder).mkdir(parents=True, exist_ok=True)
        for old in (docs / folder).glob("*.html"):
            if old not in pages and GENERATED in old.read_text(encoding="utf-8"):
                old.unlink()
    for path, html in pages.items():
        path.write_text(html, encoding="utf-8")

    urls = [base] + [base + p.relative_to(docs).as_posix() for p in pages]
    (docs / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{escape(u)}</loc></url>\n" for u in urls) + "</urlset>\n", encoding="utf-8")
    (docs / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {base}sitemap.xml\n", encoding="utf-8")
    print(f"Site: {len(episodes)} episode pages, {len(found)} topic pages")


def _local_base_url(cfg: dict) -> str:
    if cfg["podcast"].get("base_url"):
        return cfg["podcast"]["base_url"]
    remote = subprocess.run(["git", "remote", "get-url", "origin"], capture_output=True, text=True, cwd=ROOT).stdout
    m = re.search(r"github\.com[:/]([^/]+)/([^/.\s]+)", remote)
    if not m:
        raise SystemExit("Cannot tell the site URL: set podcast.base_url in config.yaml")
    return f"https://{m.group(1).lower()}.github.io/{m.group(2)}/"


if __name__ == "__main__":
    import yaml
    from . import catalog
    config = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    url = _local_base_url(config)
    load = lambda name: json.loads((ROOT / "data" / name).read_text(encoding="utf-8"))  # noqa: E731
    catalog.write_catalog(config, load("episodes.json"), load("previews.json"), ROOT / "data",
                          ROOT / "docs" / "catalog.json", url)
    write_site(config, ROOT / "docs" / "catalog.json", ROOT / "data", ROOT / "docs", url)
