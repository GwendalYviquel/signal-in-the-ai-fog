"""Cost tracking: every run appends what it consumed to data/costs.json, and COSTS.md is rebuilt.

Claude: tokens and web searches from the API's usage, estimated in USD with the prices in
config.yaml. ElevenLabs: characters synthesised (1 credit per character with the model used).
"""
from __future__ import annotations

import datetime as dt
import json
import os
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "data" / "costs.json"
REPORT = ROOT / "COSTS.md"

CLAUDE_FIELDS = ("input_tokens", "output_tokens", "cache_creation_input_tokens", "cache_read_input_tokens",
                 "web_search_requests", "api_calls")


def empty_claude_usage(model: str) -> dict:
    return {"model": model, **{f: 0 for f in CLAUDE_FIELDS}}


def add_usage(total: dict, response) -> None:
    """Add one Messages API response's usage to a running total."""
    usage = getattr(response, "usage", None)
    total["api_calls"] += 1
    if usage is None:
        return
    for field in CLAUDE_FIELDS[:4]:
        total[field] += getattr(usage, field, 0) or 0
    server = getattr(usage, "server_tool_use", None)
    total["web_search_requests"] += getattr(server, "web_search_requests", 0) or 0


def claude_usd(usage: dict, prices: dict) -> float:
    per_mtok = prices["claude_usd_per_mtok"]
    return round(usage["input_tokens"] / 1e6 * per_mtok["input"]
                 + usage["output_tokens"] / 1e6 * per_mtok["output"]
                 + usage["cache_creation_input_tokens"] / 1e6 * per_mtok["cache_write"]
                 + usage["cache_read_input_tokens"] / 1e6 * per_mtok["cache_read"]
                 + usage["web_search_requests"] / 1000 * prices["web_search_usd_per_1000"], 4)


def run_url() -> str:
    run_id = os.getenv("GITHUB_RUN_ID")
    if not run_id:
        return ""
    return f"{os.getenv('GITHUB_SERVER_URL', 'https://github.com')}/{os.getenv('GITHUB_REPOSITORY')}/actions/runs/{run_id}"


def load(path: Path = LEDGER) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else []


def record(cfg: dict, mode: str, outcome: str, claude: dict | None = None, elevenlabs_characters: int = 0,
           note: str = "", ledger: Path = LEDGER, report: Path = REPORT, now: dt.datetime | None = None) -> dict:
    """Append one run to the ledger, rebuild the report and the GitHub step summary."""
    now = now or dt.datetime.now(dt.timezone.utc)
    entry = {"time": now.replace(microsecond=0).isoformat(), "mode": mode, "outcome": outcome,
             "run_url": run_url(), "claude": None, "elevenlabs_characters": elevenlabs_characters, "note": note}
    if claude and claude["api_calls"]:
        entry["claude"] = dict(claude, usd=claude_usd(claude, cfg["costs"]))
    runs = load(ledger) + [entry]
    ledger.parent.mkdir(parents=True, exist_ok=True)
    ledger.write_text(json.dumps(runs, ensure_ascii=False, indent=1), encoding="utf-8")
    report.write_text(build_report(runs, cfg), encoding="utf-8")
    summary = os.getenv("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as f:
            f.write(f"### Cost of this run\n\n{run_line(entry)}\n")
    print(f"Cost of this run: {run_line(entry)}")
    return entry


def run_line(e: dict) -> str:
    c = e["claude"]
    claude = (f"Claude {c['input_tokens'] + c['cache_creation_input_tokens'] + c['cache_read_input_tokens']:,} in, "
              f"{c['output_tokens']:,} out, {c['web_search_requests']} searches, ≈ ${c['usd']:.2f}") if c else "Claude —"
    return f"{claude} · ElevenLabs {e['elevenlabs_characters']:,} characters"


def build_report(runs: list[dict], cfg: dict) -> str:
    prices = cfg["costs"]
    months = defaultdict(lambda: {"runs": 0, "usd": 0.0, "tokens": 0, "searches": 0, "chars": 0, "episodes": 0})
    for e in runs:
        m = months[e["time"][:7]]
        m["runs"] += 1
        m["chars"] += e["elevenlabs_characters"]
        m["episodes"] += e["mode"] == "publish" and e["outcome"] == "ok"
        if e["claude"]:
            c = e["claude"]
            m["usd"] += c["usd"]
            m["tokens"] += c["input_tokens"] + c["output_tokens"] + c["cache_creation_input_tokens"] + c["cache_read_input_tokens"]
            m["searches"] += c["web_search_requests"]
    p = prices["claude_usd_per_mtok"]
    lines = [
        "# Costs",
        "",
        "What every run consumed, Claude and ElevenLabs. Generated by `podcast/costs.py` from "
        "`data/costs.json` after each run: do not edit by hand.",
        "",
        f"Claude estimates use the prices in `config.yaml` ({cfg['generation']['model']}: "
        f"${p['input']:.2f} per million input tokens, ${p['output']:.2f} output, ${p['cache_write']:.2f} cache write, "
        f"${p['cache_read']:.2f} cache read, ${prices['web_search_usd_per_1000']:.2f} per 1,000 web searches). "
        "ElevenLabs counts characters, which are its credits with the model used.",
        "",
        "## By month",
        "",
        "| Month | Runs | Episodes published | Claude tokens | Web searches | Claude (≈ USD) | ElevenLabs characters |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for month in sorted(months, reverse=True):
        m = months[month]
        lines.append(f"| {month} | {m['runs']} | {m['episodes']} | {m['tokens']:,} | {m['searches']} | "
                     f"${m['usd']:.2f} | {m['chars']:,} |")
    untracked = [e for e in runs if "not recorded" in e["note"]]
    if untracked:
        first, last = untracked[0]["time"][:10], untracked[-1]["time"][:10]
        when = f"on {first}" if first == last else f"between {first} and {last}"
        lines += ["", f"⚠️ {len(untracked)} runs {when} called Claude before cost tracking "
                      "existed: their tokens are not in these totals. The Claude Console usage page has them."]
    lines += ["", "## Runs", "",
              "| Date (UTC) | Mode | Outcome | Claude calls | Input tokens | Output tokens | Web searches | "
              "Claude (≈ USD) | ElevenLabs characters | Note |",
              "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for e in reversed(runs):
        c = e["claude"]
        when = e["time"][:16].replace("T", " ")
        when = f"[{when}]({e['run_url']})" if e["run_url"] else when
        tokens_in = c["input_tokens"] + c["cache_creation_input_tokens"] + c["cache_read_input_tokens"] if c else None
        lines.append(" | ".join([
            f"| {when}", e["mode"], e["outcome"],
            str(c["api_calls"]) if c else "—", f"{tokens_in:,}" if c else "—",
            f"{c['output_tokens']:,}" if c else "—", str(c["web_search_requests"]) if c else "—",
            f"${c['usd']:.2f}" if c else "—", f"{e['elevenlabs_characters']:,}", e["note"] + " |"]))
    return "\n".join(lines) + "\n"
